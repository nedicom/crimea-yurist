class Command(BaseCommand):
    help = "Создаёт SEO-посадочные (города и услуги) идемпотентно."

    def add_arguments(self, parser):
        parser.add_argument("--dry-run", action="store_true",
                            help="Показать план без записи в БД")

    def handle(self, *args, **options):
        from home.models import HomePage, CityPage, ServicePage

        dry = options["dry_run"]
        home = HomePage.objects.first()
        if home is None:
            self.stderr.write("HomePage не найдена — нечего наполнять.")
            return

        created_cities = 0
        created_services = 0
        skipped = 0

        for city in CITIES:
            city_page = CityPage.objects.child_of(home).filter(slug=city["slug"]).first()

            if city_page is None:
                if not city["is_new"]:
                    self.stderr.write(
                        "! Город '{}' (slug={}) не найден и помечен как существующий — пропускаю.".format(
                            city["name"], city["slug"]))
                    continue
                payload = make_city_payload(city)
                if dry:
                    self.stdout.write("[dry] СОЗДАТЬ город: {} (/{}/)".format(payload["title"], payload["slug"]))
                    created_cities += 1
                else:
                    city_page = CityPage(**payload)
                    home.add_child(instance=city_page)
                    rev = city_page.save_revision()
                    rev.publish()
                    created_cities += 1
                    self.stdout.write(self.style.SUCCESS("+ Город: {} (/{}/)".format(
                        city_page.title, city_page.slug)))

            # Какие услуги создавать: для новых городов — все, для существующих — только новые.
            for service in SERVICES:
                if not city["is_new"] and service["core"]:
                    continue  # core-услуга уже есть в существующем городе

                slug = "{}-{}".format(service["slug_base"], city["frag"])

                # В dry-run для нового города city_page ещё None — считаем по slug-намерению.
                exists = False
                if city_page is not None:
                    exists = ServicePage.objects.child_of(city_page).filter(slug=slug).exists()
                if exists:
                    skipped += 1
                    continue

                payload = make_service_payload(service, city)
                if dry:
                    self.stdout.write("    [dry] СОЗДАТЬ услугу: {} (/{}/{}/)".format(
                        payload["title"], city["slug"], payload["slug"]))
                    created_services += 1
                    continue

                svc = ServicePage(**payload)
                city_page.add_child(instance=svc)
                rev = svc.save_revision()
                rev.publish()
                created_services += 1
                self.stdout.write("    + Услуга: {} (/{}/{}/)".format(
                    svc.title, city["slug"], svc.slug))

        self.stdout.write(self.style.SUCCESS(
            "\nГотово. Городов создано: {}, услуг создано: {}, пропущено (уже есть): {}{}".format(
                created_cities, created_services, skipped, "  [DRY-RUN, ничего не записано]" if dry else "")))
