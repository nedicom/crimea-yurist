def build_paragraph(html):
    # RichTextBlock требует объект RichText, а не строку (иначе падает get_prep_value).
    return ("paragraph", RichText(html))


def make_service_payload(service, city):
    """Возвращает dict с полями ServicePage для конкретной услуги в городе."""
    prep = city["prep"]
    title = "{} {}".format(service["base_title"], prep)
    slug = "{}-{}".format(service["slug_base"], city["frag"])

    lead = service["lead"].format(prep=prep)
    includes_html = "<ul>" + "".join("<li>{}</li>".format(i) for i in service["includes"]) + "</ul>"
    city_para = (
        "Мы работаем {prep} с 2014 года и знаем практику местных судов "
        "({court}). Первая консультация — бесплатно: оценим перспективы дела и предложим "
        "решение. Звоните по телефону +7 978 910-42-97 или оставьте заявку на сайте."
    ).format(prep=prep, court=city["court"])

    content = [
        ("heading", "{} {}: профессиональная помощь".format(service["base_title"], prep)),
        build_paragraph("<p>{}</p>".format(lead)),
        ("heading", "Что входит в услугу"),
        build_paragraph(includes_html),
        ("heading", "Когда стоит обратиться"),
        build_paragraph("<p>{}</p>".format(service["audience"])),
        ("heading", "Почему выбирают нас {}".format(prep)),
        build_paragraph("<p>{}</p>".format(city_para)),
    ]

    seo_title = "{} — цены и бесплатная консультация".format(title)
